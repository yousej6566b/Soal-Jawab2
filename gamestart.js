// ==============================================
// OPEN QUESTION (draws from per-card bank, random, no repeat)
// ==============================================
function openQuestion(team,cardIdx,diff,subIdx,catKey){
  if(isQuestionActive) return;
  if(isQuestionUsed(team,cardIdx,diff,subIdx)){
    showToast('❌ هذا السؤال مستخدم مسبقاً!','error');
    return;
  }

  const teamCards=team===1?team1Cards:team2Cards;
  const card=teamCards[cardIdx];
  if(!card){showToast('❌ بطاقة غير موجودة!','error');return;}

  const bankKey=catKey+'_'+card.title+'_'+diff;
  const bank=cardQuestionBanks[bankKey];
  
  if(!bank||bank.length===0){
    showToast('❌ لا توجد أسئلة متاحة لهذا الكرت!','error');
    usedQuestions.push(team+'_'+cardIdx+'_'+diff+'_'+subIdx);
    updateDifficultyButtons();
    return;
  }

  // Track used question indices per bank
  if(!usedQuestionTracker[bankKey]) usedQuestionTracker[bankKey]=[];
  const used=usedQuestionTracker[bankKey];
  
  // Find available indices (not yet used in this game)
  const available=[];
  for(let i=0;i<bank.length;i++){
    if(!used.includes(i)) available.push(i);
  }
  
  if(available.length===0){
    showToast('❌ انتهت أسئلة هذا القسم! العب جولة جديدة للمزيد','error');
    usedQuestions.push(team+'_'+cardIdx+'_'+diff+'_'+subIdx);
    updateDifficultyButtons();
    return;
  }

  // Pick random available question
  const randIdx=available[Math.floor(Math.random()*available.length)];
  used.push(randIdx);
  
  const q=bank[randIdx];
  
  // Mark button as used  
  markQuestionUsed(team,cardIdx,diff,subIdx);

  isQuestionActive=true;
  currentTeam=team;
  currentQuestion={team,cardIdx,diff,subIdx,catKey,data:q};

  const overlay=document.getElementById('gsQuestionOverlay');
  overlay.classList.add('active');

  const cat=getCatInfo(catKey);
  document.getElementById('gsQCategory').innerHTML=cat.icon+' '+cat.label+' - '+card.title;
  const diffEl=document.getElementById('gsQDiff');
  diffEl.textContent=diff===200?'سهل':diff===300?'متوسط':'صعب';
  diffEl.className='gs-q-diff e'+diff;
  document.getElementById('gsQPoints').textContent='🏆 '+diff;
  document.getElementById('gsQPoints').classList.toggle('doubled',doubleActive);
  document.getElementById('gsQText').textContent=q.q;
  document.getElementById('gsQAnswer').textContent=q.a;
  document.getElementById('gsQAnswer').classList.remove('show');
  document.getElementById('gsQRevealBtn').style.display='block';
  document.getElementById('gsQTeamSelect').classList.remove('show');
  document.getElementById('gsQCloseBtn').classList.remove('show');
  generateQuestionImage(catKey,diff);
  doubleActive=false;
  wheelMultiplier=1;
  updatePowerups();
  playSound('click');
}

