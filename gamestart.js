  function awardPoints(team) {
    if (!currentQuestion) return;

    if (team === 0) {
      playSound('reveal');
      closeQuestion();
      showToast('❌ ولا أحد جاوب! السؤال ضاع', 'error');
      return;
    }

    const diff = currentQuestion.diff;
    let points = diff * wheelMultiplier;
    if (doubleActive) points *= 2;

    if (team === 1) {
      team1Score += points;
      if (team1Score > WIN_SCORE) team1Score = WIN_SCORE;
    } else {
      team2Score += points;
      if (team2Score > WIN_SCORE) team2Score = WIN_SCORE;
    }

    playSound('correct');

    currentTeam = currentTeam === 1 ? 2 : 1;
    updateTurn();

    const teamName = team === 1 ? document.getElementById('gsTeamName1').textContent : document.getElementById('gsTeamName2').textContent;
    let msg = '🎉 ' + teamName + ' حصل على ' + points + ' نقطة!';
    if (doubleActive) msg += ' (مضاعف)';
    if (wheelMultiplier > 1) msg += ' (دوارة الحظ ×' + wheelMultiplier + ')';
    showToast(msg, 'success');

    updateScore();
    updateTurn();

    closeQuestion();

    if (team1Score >= WIN_SCORE) { showWinner(1); } else if (team2Score >= WIN_SCORE) { showWinner(2); }
  }

