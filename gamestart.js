  function startConfetti() {
    const canvas = document.getElementById('gsConfettiCanvas');
    canvas.classList.add('active');
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
    const ctx = canvas.getContext('2d');
    const particles = [];
    for (let i = 0; i < 150; i++) {
      particles.push({
        x: Math.random() * canvas.width,
        y: Math.random() * canvas.height - 100,
        vx: (Math.random() - 0.5) * 4,
        vy: Math.random() * 3 + 2,
        w: Math.random() * 8 + 4,
        h: Math.random() * 8 + 4,
        color: 'hsl(' + (Math.random() * 360) + ',80%,60%)',
        rot: Math.random() * 360,
        rv: (Math.random() - 0.5) * 5,
        life: Math.random() * 100 + 50
      });
    }
    let frame = 0;

    function animateConfetti() {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      particles.forEach(p => {
        p.x += p.vx;
        p.y += p.vy;
        p.rot += p.rv;
        p.vy += 0.05;
        p.life--;
        ctx.save();
        ctx.translate(p.x, p.y);
        ctx.rotate(p.rot * Math.PI / 180);
        ctx.globalAlpha = Math.min(1, p.life / 50);
        ctx.fillStyle = p.color;
        ctx.fillRect(-p.w / 2, -p.h / 2, p.w, p.h);
        ctx.restore();
      });
      frame++;
      if (frame < 300 && document.getElementById('gsWinnerOverlay').classList.contains('active'))
        requestAnimationFrame(animateConfetti);
      else { canvas.classList.remove('active'); }
    }
    animateConfetti();
  }

