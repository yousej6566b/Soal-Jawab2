  // ==============================================
  // POWER-UPS
  // ==============================================
  function usePowerup(type) {
    if (!isQuestionActive) {
      showToast('❌ يجب فتح سؤال أولاً!', 'error');
      return;
    }
    const pu = powerups[currentTeam][type];
    const now = Date.now();
    if (pu.used >= MAX_USES) {
      showToast('❌ انتهت استخدامات هذه الوسيلة!', 'error');
      return;
    }
    if (now - pu.lastUse < COOLDOWN) {
      const mins = Math.ceil((COOLDOWN - (now - pu.lastUse)) / 60000);
      showToast('⏳ انتظر ' + mins + ' دقيقة قبل استخدام هذه الوسيلة', 'error');
      return;
    }

    switch (type) {
      case 'double':
        doubleActive = true;
        document.getElementById('gsQPoints').classList.add('doubled');
        showToast('💰 تم تفعيل تدبيل النقاط!', 'success');
        pu.used++;
        pu.lastUse = now;
        break;
      case 'wheel':
        document.getElementById('gsWheelOverlay').classList.add('active');
        drawWheel();
        pu.used++;
        pu.lastUse = now;
        return;
      case 'fifty':
        showToast('✂️ تم حذف إجابة (50/50)', 'success');
        pu.used++;
        pu.lastUse = now;
        break;
      case 'steal':
        if (currentTeam === 1 && team2Score > 0) {
          const stolen = Math.min(team2Score, 500);
          team2Score -= stolen;
          team1Score += stolen;
          showToast('🦅 تم سرقة ' + stolen + ' نقطة!', 'success');
        } else if (currentTeam === 2 && team1Score > 0) {
          const stolen = Math.min(team1Score, 500);
          team1Score -= stolen;
          team2Score += stolen;
          showToast('🦅 تم سرقة ' + stolen + ' نقطة!', 'success');
        } else { showToast('❌ لا توجد نقاط للسرقة!', 'error'); return; }
        updateScore();
        pu.used++;
        pu.lastUse = now;
        updatePowerups();
        closeQuestion();
        break;
      case 'skip':
        showToast('⏭️ تم تخطي السؤال!', 'info');
        pu.used++;
        pu.lastUse = now;
        updatePowerups();
        closeQuestion();
        break;
    }
    updatePowerups();
  }

  function updatePowerups() {
    const buttons = document.querySelectorAll('.gs-pu-btn');
    buttons.forEach(btn => {
      const type = btn.dataset.pu;
      const pu = powerups[currentTeam][type];
      const now = Date.now();
      btn.disabled = false;
      btn.classList.remove('on-cooldown');
      if (pu.used >= MAX_USES) { btn.disabled = true;
        btn.title = 'انتهت الاستخدامات'; } else if (now - pu.lastUse < COOLDOWN) {
        const remaining = Math.ceil((COOLDOWN - (now - pu.lastUse)) / 1000);
        const mins = Math.floor(remaining / 60);
        const secs = remaining % 60;
        btn.classList.add('on-cooldown');
        btn.querySelector('.pu-cooldown').textContent = mins + ':' + (secs < 10 ? '0' : '') + secs;
        if (pu.used === 0) btn.disabled = false;
        else btn.disabled = true;
      } else {
        btn.title = '';
      }
    });
  }

