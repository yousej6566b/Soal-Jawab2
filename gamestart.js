  function drawWheel() {
    const canvas = document.getElementById('gsWheelCanvas');
    const ctx = canvas.getContext('2d');
    const cx = 110,
      cy = 110,
      r = 100,
      arc = Math.PI * 2 / wheelSectors.length;
    ctx.clearRect(0, 0, 220, 220);
    wheelSectors.forEach((s, i) => {
      const start = i * arc - Math.PI / 2;
      ctx.beginPath();
      ctx.moveTo(cx, cy);
      ctx.arc(cx, cy, r, start, start + arc);
      ctx.closePath();
      ctx.fillStyle = s.color + '88';
      ctx.fill();
      ctx.strokeStyle = 'rgba(255,255,255,0.2)';
      ctx.lineWidth = 1;
      ctx.stroke();
      ctx.save();
      ctx.translate(cx, cy);
      ctx.rotate(start + arc / 2);
      ctx.fillStyle = '#fff';
      ctx.font = '700 10px Tajawal,sans-serif';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(s.label, 55, 0);
      ctx.restore();
    });
  }

  function spinWheel() {
    if (wheelSpinning) return;
    wheelSpinning = true;
    const btn = document.getElementById('gsWheelSpinBtn');
    btn.disabled = true;
    const canvas = document.getElementById('gsWheelCanvas');
    const ctx = canvas.getContext('2d');
    let angle = 0,
      speed = 15 + Math.random() * 10;
    const targetAngle = Math.random() * Math.PI * 2;
    const totalSpin = Math.PI * 2 * (5 + Math.random() * 3) + targetAngle;
    let spun = 0;

    function animate() {
      angle += speed * 0.05;
      spun += speed * 0.05;
      ctx.clearRect(0, 0, 220, 220);
      ctx.save();
      ctx.translate(110, 110);
      ctx.rotate(angle);
      ctx.translate(-110, -110);
      drawWheel();
      ctx.restore();
      speed *= 0.97;
      if (spun < totalSpin && speed > 0.3) {
        requestAnimationFrame(animate);
      } else {
        wheelSpinning = false;
        const idx = Math.floor(((angle % (Math.PI * 2)) + Math.PI * 2) % (Math.PI * 2) / (Math.PI * 2 / wheelSectors.length)) % wheelSectors.length;
        const result = wheelSectors[idx];
        document.getElementById('gsWheelResult').textContent = '🎉 ' + result.label;
        document.getElementById('gsWheelResult').style.display = 'block';
        btn.disabled = false;
        if (result.mult) wheelMultiplier = result.mult;
        else if (result.points) {
          if (currentTeam === 1) team1Score += result.points;
          else team2Score += result.points;
          updateScore();
        }
        showToast('🎡 دوارة الحظ: ' + result.label, 'success');
      }
    }
    animate();
  }

