function renderBoard(){
  const board=document.getElementById('gsBoard');
  board.innerHTML='';
  const grid=document.createElement('div');grid.className='gs-cards-grid';
  const allCards=[];
  team1Cards.forEach((c,idx)=>{allCards.push({card:c, idx:idx, team:1});});
  team2Cards.forEach((c,idx)=>{allCards.push({card:c, idx:idx, team:2});});
  allCards.forEach((item)=>{
    const cat=getCatInfo(item.card.cat);
    grid.appendChild(createGameCard(item.card,item.idx,item.team,cat));
  });
  board.appendChild(grid);
  updateScore();
  updateTurn();
  updatePowerups();
  updateProgress();
}

